document.addEventListener('DOMContentLoaded', function () {
  function getAmsterdamStatusTime() {
    var now = new Date();
    var parts = new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Europe/Amsterdam',
      weekday: 'short',
      hour: '2-digit',
      minute: '2-digit',
      hourCycle: 'h23'
    }).formatToParts(now);

    function value(type) {
      var p = parts.find(function (x) { return x.type === type; });
      return p ? p.value : '';
    }

    return {
      weekday: value('weekday'),
      minutes: Number(value('hour') || 0) * 60 + Number(value('minute') || 0)
    };
  }

  function renderStatus() {
    var statusTime = getAmsterdamStatusTime();
    var minutes = statusTime.minutes;
    var weekday = statusTime.weekday;
    var isWorkday = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'].indexOf(weekday) !== -1;
    var online = isWorkday && minutes >= 540 && minutes < 1260; /* werkdagen 09:00–20:59 */
    var closedCopy;

    if (weekday === 'Sat' || weekday === 'Sun' || (weekday === 'Fri' && minutes >= 1260)) {
      closedCopy = 'Maandag vanaf 09:00';
    } else if (isWorkday && minutes < 540) {
      closedCopy = 'Vandaag vanaf 09:00';
    } else {
      closedCopy = 'Morgen vanaf 09:00';
    }

    document.querySelectorAll('[data-ondex-status]').forEach(function (box) {
      var title = box.querySelector('[data-status-title]');
      var copy = box.querySelector('[data-status-copy]');
      var host = box.closest('.ondex-availability') || box.parentElement;
      var dot = host ? host.querySelector('i') : null;

      if (title) title.textContent = online ? 'Online' : 'Offline';
      if (copy) copy.textContent = online ? 'Direct bereikbaar' : closedCopy;

      if (host) {
        host.classList.toggle('is-offline', !online);
        host.setAttribute('aria-label',
          online ? 'Online, direct bereikbaar' : 'Offline, ' + closedCopy
        );
      }

      if (dot) {
        dot.style.background = online ? '#25D366' : '#dc2626';
        dot.style.boxShadow = online
          ? '0 0 0 3px rgba(37,211,102,.12)'
          : '0 0 0 4px rgba(220,38,38,.10),0 0 8px rgba(220,38,38,.28)';
      }
    });
  }

  renderStatus();
  window.setInterval(renderStatus, 60000);
});

